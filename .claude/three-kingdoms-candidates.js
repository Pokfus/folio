// afterwards from the same starting commit, and the two tables turned out NOT to be nested:
// each covers names the other misses. These are the rows the second pass has and the
// shipped table has not - 483 romanisations, 29 spelling fixes and 15 glyph repairs, keyed
// by their `from` string and deduped against what `.claude/fetch-book.js` already declares.
//
// The second pass also measured the book's residue honestly, over the CHAPTERS ONLY (a
// whole-file sweep is inflated by the About page, which deliberately prints Wade-Giles
// illustrations): 669 Wade-Giles-looking marks remain, of which 611 are CORRECT - 602 are
// the pinyin Lu of 吕 and 略, and 9 are the French melee. The other 58, across 18 forms, are
// the real gap. The commonest single case is the SECOND element of a two-token personal name
// whose FIRST element a shorter row has already converted; 24 of the 58 are one name.
// A hyphen guard was suspected as the cause and MEASURED RATHER THAN ASSERTED: over the five
// commonest forms, 43 occurrences carry 8 that sit beside a hyphen, so that is not it.
//
// WHY THEY ARE NOT SHIPPED. A row is only allowed into the importer once it has FIRED on this
// book's own text - CLAUDE.md's rule that a dead row is a defect rather than spare capacity -
// and merging two tables changes which rows fire, because `applyRoman` sorts longest-first and
// a longer row shadows a shorter one. So the union has to be spliced in, the book rebuilt with
// `--force`, the dead-row report read, the dead rows struck out, the book rebuilt again to
// prove the prune byte-neutral, and the residue re-measured - after which every figure quoted
// in the importer's commentary, the book's About page, the plan doc and the changelog has to be
// corrected to what was actually measured. That is roughly two full build cycles and is batch
// B6b's work, not something to be half-done.
//
// NOTHING READS THIS FILE. It is research kept so the next pass does not repeat it.

