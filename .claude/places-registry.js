/* ============================================================================
   places-registry.js — THE ONE READER OF THE PLACES REGISTRY, for every helper and test in .claude/
   (Atlas v2 Phase 3a; docs/atlas-v2-design.md §2.8, §7 "Phase 3a — as built").

     const R = require("./places-registry.js");
     const reg = R.loadRegistry();           // { rows: Map id → row, byName: Map folded name → [row…], entities, cardsOf }
     reg.rows.get("city:1159151545")          // Athens, from the gazetteer
     reg.rows.get("pl:q173527")               // Knossos, from atlas/data/places.js (the Phase 3 places the cards need)
     reg.rows.get("pol:rome")                 // Rome the polity, from history.bin's entity table (kind "polity")
     reg.cardsOf("pol:rome")                  // the cards that link the polity (the entity table's `cards`, Phase 2b)

   WHAT THE REGISTRY IS. Three generated files, read as one table of places a card may point at by id:
     · atlas/data/gazetteer.js   — the present-day places the Atlas names (Phase 1c; countries, provinces, cities, seas,
                                   lakes, rivers, islands, ranges, regions), ids `adm0:…`, `adm1:…`, `city:…`, `sea:…`…
     · atlas/data/places.js      — the places the CARDS need that the gazetteer does not carry (Phase 3a: ancient cities and
                                   sites, caves, battlefields, mountains, historical regions), ids `pl:q<Wikidata number>`,
                                   generated by .claude/atlas-build/build-places.js from places-spec.json, every row
                                   Wikidata-checked (an item, its coordinate, its class)
     · atlas/data/history.bin    — the entity table (Phase 2a/2b): every polity `pol:<key>` with its span, QID, Wikipedia
                                   title and the cards that link it (polity-spec.json's links, carried by build-history.js)
   A card's `places` (the heavy field, data-extra/) is an array of these ids. Nothing in the site reads it yet (3b).

   NAMES. `byName` folds (diacritics and case stripped) the display name and every alias of every row, so a lookup never
   depends on spelling; a name shared by several rows (Moscow the city and the oblast; Georgia; Olympia in Greece and in
   Washington) returns them all — the CALLER decides by kind and distance, or reports an ambiguity. Nothing here guesses.
   ============================================================================ */
"use strict";
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const DATA = path.join(ROOT, "atlas", "data");
const GAZETTEER = path.join(DATA, "gazetteer.js");
const PLACES = path.join(DATA, "places.js");
const HISTORY = path.join(DATA, "history.bin");

/* the kinds a registry row may carry: the gazetteer's fifteen (§2.6 v0), the Phase 3 additions, and the entity kinds */
const GAZETTEER_KINDS = ["country", "admin1", "capital", "city", "town", "sea", "ocean", "strait", "gulf", "lake", "river", "island", "island-group", "range", "region"];
const PLACE_KINDS = GAZETTEER_KINDS.concat(["site", "mountain", "cape"]);          // places.js may add a site (a cave, a temple, a battlefield, an ancient city), a mountain, a cape
const ENTITY_KINDS = ["polity", "people"];
const KINDS = PLACE_KINDS.concat(ENTITY_KINDS);
const ID_RE = /^(adm0|adm1|city|sea|reg|pt|lake|river|pl|pol):[A-Za-z0-9_.:-]+$/;

const fold = (x) => String(x == null ? "" : x).normalize("NFD").replace(/[̀-ͯ]/g, "").toLowerCase().replace(/[’‘`]/g, "'").replace(/\s+/g, " ").trim();
const km = (a, b) => { const R = 6371, d = Math.PI / 180; const dLat = (b[1] - a[1]) * d, dLon = (b[0] - a[0]) * d; const s = Math.sin(dLat / 2) ** 2 + Math.cos(a[1] * d) * Math.cos(b[1] * d) * Math.sin(dLon / 2) ** 2; return 2 * R * Math.asin(Math.min(1, Math.sqrt(s))); };

function readTable(file, globalName) {
  const w = {};
  // eslint-disable-next-line no-new-func
  new Function("window", fs.readFileSync(file, "utf8"))(w);
  const t = w[globalName];
  if (!t || !Array.isArray(t.cols) || !Array.isArray(t.rows)) throw new Error(file + " does not assign window." + globalName + " with cols and rows");
  const col = {}; t.cols.forEach((c, i) => { col[c] = i; });
  const rows = t.rows.map((r) => { const o = {}; for (const c of t.cols) { const v = r[col[c]]; o[c] = v == null ? 0 : v; } return o; });
  // `within` is stored as the container's row index + 1 (0 = none) in the gazetteer; places.js stores the id itself
  for (const o of rows) if (typeof o.within === "number") o.within = o.within ? rows[o.within - 1].id : "";
  for (const o of rows) { if (o.qid && typeof o.qid === "number") o.qid = "Q" + o.qid; o.aliases = Array.isArray(o.aliases) ? o.aliases.flatMap((a) => String(a).split("|")).map((a) => a.trim()).filter(Boolean) : []; if (o.wiki === 1) o.wiki = o.name; if (!o.wiki) o.wiki = ""; }
  return { table: t, rows };
}

function readEntities() {
  if (!fs.existsSync(HISTORY)) return [];
  const F = require(path.join(ROOT, "atlas", "atlas-format.js"));
  const T = F.read(new Uint8Array(fs.readFileSync(HISTORY)), { headerOnly: true });
  return (T.header.entities || []).map((e) => ({ id: e.id, name: e.name, kind: e.kind, key: e.key || e.id.replace(/^pol:/, ""), span: e.span || null, qid: e.qid || "", wiki: e.wiki || "", aliases: [], cards: (e.cards || []).slice(), partners: e.partners || null, at: null, within: "" }));
}

function loadRegistry(opts) {
  opts = opts || {};
  const rows = new Map(), byName = new Map(), from = new Map();
  const add = (row, src) => { if (rows.has(row.id)) throw new Error("registry: duplicate id " + row.id + " (" + from.get(row.id) + " and " + src + ")"); rows.set(row.id, row); from.set(row.id, src); const names = [row.name].concat(row.aliases || []); for (const n of names) { const k = fold(n); if (!k) continue; let l = byName.get(k); if (!l) byName.set(k, l = []); if (!l.includes(row)) l.push(row); } };
  const gz = readTable(GAZETTEER, "ATLAS_GAZETTEER");
  for (const r of gz.rows) add(r, "gazetteer");
  let places = { table: null, rows: [] };
  if (fs.existsSync(PLACES)) { places = readTable(PLACES, "ATLAS_PLACES"); for (const r of places.rows) add(r, "places"); }
  const entities = opts.entities === false ? [] : readEntities();
  for (const e of entities) if (e.kind === "polity" || e.kind === "people") add(e, "history");
  const cardsOf = (id) => { const e = rows.get(id); return e && e.cards ? e.cards.slice() : []; };
  const source = (id) => from.get(id) || null;
  return { rows, byName, entities, cardsOf, source, gazetteer: gz.table, places: places.table, fold, km };
}

/* is `id` a place id the registry resolves? (a string check first, so a typo is named as such) */
function validId(id) { return typeof id === "string" && ID_RE.test(id); }

module.exports = { loadRegistry, readTable, readEntities, fold, km, validId, KINDS, PLACE_KINDS, GAZETTEER_KINDS, ENTITY_KINDS, GAZETTEER, PLACES, HISTORY, DATA };
