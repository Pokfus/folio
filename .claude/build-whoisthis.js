/* build-whoisthis.js — the pool of "Who is this?", the portrait minigame (2026-11-19, on request;
   docs/minigames.md "Who is this?").

     node .claude/build-whoisthis.js           write whoisthis.js
     node .claude/build-whoisthis.js --check   fail when whoisthis.js differs from what it would write (CI)
     node .claude/build-whoisthis.js --list    print every card in the pool with its picture's title and caption

   WHY A GENERATED LIST. A card's picture is a HEAVY field (`image`, in data-extra/<prefix>.js, one lazy file per
   collection), so the page cannot tell which cards carry a portrait without fetching every collection's heavy
   half — tens of megabytes. The rule is therefore applied HERE, offline, over the whole corpus (card-io.js joins
   the two halves), and whoisthis.js carries only the card ids. The page intersects that list with
   `gameCardIdSet()` (availability and the difficulty bar stay live), deals five with `dayPick`, and fetches the
   heavy half of those five cards alone.

   THE RULE — a card is in the pool when ALL of these hold:
     1. its tags include `person` (the corpus's own kind tag for an individual), and none of `mythology`, `hero`,
        `deity`, `god`, `legend` (a historical figure, not a figure of myth);
     2. it is not an artwork card (`artwork: true` — its picture is a work of art, the dormant Picture round's);
     3. it carries a picture (`image.src`);
     4. the picture's title or caption uses a word that says it DEPICTS someone — portrait, bust, photograph,
        photographed, photo, statue, likeness, effigy — and
     5. names the card's person: one word of three letters or more of the answer (titles such as "Emperor" and
        particles such as "von" left out) appears in the title or caption;
     6. it is not in EXCLUDE below — the cards a human read of every match rejected, each with its reason.
   Nothing is authored but the exclusions: the tags, the pictures and the captions are the cards' own. */
"use strict";
const fs = require("fs");
const path = require("path");
const { loadCards } = require("./card-io.js");

const ROOT = path.join(__dirname, "..");
const OUT = path.join(ROOT, "whoisthis.js");

const NOT_HISTORICAL = new Set(["mythology", "hero", "deity", "god", "legend"]);
const DEPICTS = /\b(portrait|portraits|bust|photograph|photographed|photo|statue|likeness|effigy)\b/i;
const NAME_STOP = new Set(["the", "of", "and", "von", "van", "de", "der", "la", "le", "great", "emperor", "king",
  "queen", "saint", "st", "pope", "sir", "lord", "duke", "prince", "ii", "iii", "iv", "vi", "vii", "viii"]);
/* Read by hand over every match (2026-11-19): what the picture actually shows is not the person. */
const EXCLUDE = {
  "gr-496": "the picture is the remains of Phidias's workshop at Olympia, not Phidias",
  "gr-995": "Asclepius is a god, tagged person",
  "gr-876": "a coin with Mark Antony on the other face: two people, and Antony can be a decoy",
  "wh-384": "a punch-marked coin of the period; the caption says no likeness of him survives",
  "cnh-228": "the horse statue at Huo Qubing's tomb, not him",
  "rm-441": "the fleet's cistern at Misenum, not Anicetus",
  "ru-045": "a monument to Prince Mal, not Igor",
  "ww2-382": "a group photograph of Weidling and his staff: no single face to name",
};

const fold = (s) => String(s || "").normalize("NFD").replace(/[̀-ͯ]/g, "").toLowerCase();
function nameWords(c) {
  return fold(c.answerText || c.answer).replace(/\(.*?\)/g, "").split(/[^a-z]+/).filter((t) => t.length >= 3 && !NAME_STOP.has(t));
}
function inPool(c) {
  const tags = Array.isArray(c.tags) ? c.tags : [];
  if (tags.indexOf("person") < 0 || tags.some((t) => NOT_HISTORICAL.has(t))) return false;
  if (c.artwork) return false;
  const im = c.image;
  if (!im || typeof im !== "object" || !im.src) return false;
  const said = String(im.title || "") + " " + String(im.desc || "");
  if (!DEPICTS.test(said)) return false;
  const words = nameWords(c), hay = fold(said);
  if (!words.length || !words.some((w) => hay.indexOf(w) >= 0)) return false;
  return !(c.id in EXCLUDE);
}

const { cards } = loadCards();
const pool = cards.filter(inPool);
const missing = Object.keys(EXCLUDE).filter((id) => !cards.some((c) => c.id === id));
if (missing.length) { console.error("build-whoisthis: EXCLUDE names cards that do not exist: " + missing.join(", ")); process.exit(1); }

const args = process.argv.slice(2);
if (args.includes("--list")) {
  pool.forEach((c) => console.log(c.id + " | " + c.answerText + " | " + (c.image.title || "") + " | " + String(c.image.desc || "").slice(0, 140)));
  console.log(pool.length + " cards");
  process.exit(0);
}

const text =
  "/* Who is this? — the portrait minigame's pool (2026-11-19, on request; docs/minigames.md \"Who is this?\").\n" +
  "   GENERATED by .claude/build-whoisthis.js from the cards (data.js + data-extra/) — never hand-edit; re-run the builder.\n" +
  "   Lazy: loaded by the `whoisthis` bundle when the game opens, never on the eager path.\n\n" +
  "   sources: the cards' own pictures and captions (each card's `image`, credited on the card); nothing here is new content.\n\n" +
  "   ids: every card whose picture depicts its own person — the rule is in the builder's header. The page intersects\n" +
  "   this list with gameCardIdSet() and fetches the five dealt cards' heavy halves for the pictures. */\n" +
  "window.WHOISTHIS = {\n  ids: " + JSON.stringify(pool.map((c) => c.id)) + ",\n};\n";

if (args.includes("--check")) {
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
  if (cur !== text) {
    console.error("build-whoisthis --check: whoisthis.js is out of date — run node .claude/build-whoisthis.js");
    process.exit(1);
  }
  console.log("build-whoisthis --check: whoisthis.js is current (" + pool.length + " cards).");
  process.exit(0);
}
fs.writeFileSync(OUT, text);
console.log("build-whoisthis: wrote whoisthis.js (" + pool.length + " cards).");
