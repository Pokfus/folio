#!/usr/bin/env node
/* build-polity-names.js — atlas/data/polity-names.js, the display-name overrides (Atlas v2 Phase 4, task 0c)

     node .claude/atlas-build/build-polity-names.js [--install] [--check]

   Reads polity-names.json (the overrides a person wrote from audit-polity-names.js's report, each naming its Wikidata evidence), verifies them against the committed cache
   (audit-polity-names.js --check) and writes atlas/data/polity-names.js: { names: { entityId: [[from, to, name, qid], …] }, evidence: { qid: "…" } }. The Atlas applies it at display
   time — the label layout, the place card and the stack show `name` in the years from–to and the Cliopatria name in every other — and nothing in history.bin changes.
   `sources` is empty: the file holds Folio's display strings; each entry's evidence (a Wikidata item and its two dates, Wikidata being CC0) is in the entry. --check regenerates in memory
   and exits 1 when the committed file lags. */
"use strict";
const fs = require("fs"), path = require("path"), cp = require("child_process");
const HERE = __dirname, ROOT = path.join(HERE, "..", "..");
const SPEC = JSON.parse(fs.readFileSync(path.join(HERE, "polity-names.json"), "utf8")), OUT = path.join(ROOT, "atlas", "data", "polity-names.js");
const r = cp.spawnSync(process.execPath, [path.join(HERE, "audit-polity-names.js"), "--check"], { encoding: "utf8" });
if (r.status !== 0) { process.stderr.write(r.stderr || r.stdout); process.exit(1); }
const names = {}, evidence = {};
for (const o of SPEC.overrides.slice().sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : a.from - b.from))) { (names[o.id] = names[o.id] || []).push([o.from, o.to, o.name, o.qid]); evidence[o.qid] = o.evidence; }
const body = `/* sources: [] */
/* atlas/data/polity-names.js — GENERATED by .claude/atlas-build/build-polity-names.js from polity-names.json (docs/atlas-v2-design.md §7 "Phase 4 — as built"). Do not edit.
   Display names for polities in the years Wikidata dates a different name for the same ground; the Cliopatria name stands in every other year. history.bin is untouched. */
window.ATLAS_POLITY_NAMES = ${JSON.stringify({ format: 1, names, evidence })};
`;
if (process.argv.includes("--check")) {
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
  if (cur !== body) { console.error("atlas/data/polity-names.js lags polity-names.json: run build-polity-names.js --install"); process.exit(1); }
  console.log("build-polity-names --check ok: " + SPEC.overrides.length + " overrides");
} else if (process.argv.includes("--install")) { fs.writeFileSync(OUT, body); console.log("wrote " + path.relative(ROOT, OUT) + " (" + body.length + " bytes)"); }
else process.stdout.write(body);
