#!/usr/bin/env node
/* build-country-names.js — atlas/data/country-names.js: the present-day countries by their Atlas name, and how v1 spelled them (Atlas v2 Phase 5; docs/atlas-v2-phase5-plan.md §4.4, §5).

     node .claude/atlas-build/build-country-names.js [--install] [--check]

   Three readers of app.js need "the list of present-day countries" and used to take it from world.js (258 shapes): the account page's countries meter, the *Cartographer* and *Circumnavigator* badges, and the Settings
   "Atlas home" picker. world.js is deleted in Phase 5, so they read this file: the gazetteer's `country` rows (257: name and label point), built from it and from card-faces.js, which joined each of world.js's names to the
   Atlas entity it is (`layers.world`: v1 name → `adm0:…`):

       window.ATLAS_COUNTRIES = { format: 1, countries: [[name, lon, lat], …], v1: { "<v1 name>": "<Atlas name>", … }, gone: [v1 names with no Atlas country] }

   `v1` lists only the names that DIFFER (56 of 258: "S. Sudan" → "South Sudan", "Czechia" → "Czechia" is not listed because it is the same). It is what the boot migration of `placesSeen` reads (a reader who opened "S. Sudan" on v1's globe has
   `placesSeen["S. Sudan"]`; the new Atlas names the country "South Sudan", so the key is copied, keeping the old one), what the picker uses to select a stored home, and what Find it uses to write a country it teaches.
   `gone` is what has no country row (a reef), counted by no meter. A pure function of gazetteer.js and card-faces.js; byte-identical on every run. --check: regenerate in memory, compare, exit 1 when it lags. */
"use strict";
const fs = require("fs"), path = require("path"), crypto = require("crypto");
const HERE = __dirname, ROOT = path.join(HERE, "..", "..");
const OUT = path.join(ROOT, "atlas", "data", "country-names.js");
const { headerSources } = require("./fetch-sources.js");
const load = (f) => { const p = path.join(ROOT, f); delete require.cache[require.resolve(p)]; global.window = {}; require(p); return global.window; };
function build() {
  const G = load("atlas/data/gazetteer.js").ATLAS_GAZETTEER, F = load("atlas/data/card-faces.js").ATLAS_CARD_FACES;
  const ix = Object.fromEntries(G.cols.map((c, i) => [c, i]));
  const rows = G.rows.filter((r) => r[ix.kind] === "country");
  const byId = new Map(rows.map((r) => [r[ix.id], r]));
  const countries = rows.map((r) => [r[ix.name], Math.round(r[ix.at][0] * 100) / 100, Math.round(r[ix.at][1] * 100) / 100]).sort((a, b) => (a[0] < b[0] ? -1 : 1));
  const v1 = {}, gone = [];
  for (const [name, row] of Object.entries(F.layers.world)) {
    const g = byId.get(row[0]);
    if (!g) { gone.push(name); continue; }
    if (g[ix.name] !== name) v1[name] = g[ix.name];
  }
  return { countries, v1, gone: gone.sort() };
}
const r = build();
const digest = crypto.createHash("sha256").update(JSON.stringify(r)).digest("hex").slice(0, 16);
const body = "/* sources: " + JSON.stringify(headerSources(["ne-10m-admin0"])) + " */\n" +
  "/* atlas/data/country-names.js — GENERATED by .claude/atlas-build/build-country-names.js from gazetteer.js and card-faces.js (docs/atlas-v2-phase5-plan.md §4.4). Do not edit. The present-day countries by their Atlas name with a label point, and the\n   56 names v1's globe spelled otherwise (the progress register `placesSeen` keyed them by those). */\n" +
  "window.ATLAS_COUNTRIES = " + JSON.stringify({ format: 1, digest, countries: r.countries, v1: r.v1, gone: r.gone }).replace(/\],\[/g, "],\n[") + ";\n";
if (process.argv.includes("--check")) {
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
  if (cur !== body) { console.error("atlas/data/country-names.js lags its inputs: run build-country-names.js --install"); process.exit(1); }
  console.log(`build-country-names --check ok: ${r.countries.length} countries, ${Object.keys(r.v1).length} v1 spellings, ${r.gone.length} v1 names with no country`);
} else if (process.argv.includes("--install")) { fs.writeFileSync(OUT, body); console.log(`wrote atlas/data/country-names.js (${body.length} bytes): ${r.countries.length} countries, ${Object.keys(r.v1).length} v1 spellings, gone: ${r.gone.join(", ")}`); }
else process.stdout.write(body);
