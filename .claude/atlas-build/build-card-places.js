#!/usr/bin/env node
/* build-card-places.js — the LIGHT card-to-places index: atlas/data/card-places.js (Atlas v2 Phase 3b, decision 4;
   docs/atlas-v2-design.md §2.8, §7 "Phase 3b — as built").

     node .claude/atlas-build/build-card-places.js [--install] [--dry] [--check]

   WHAT IT IS. A card's `places` is a HEAVY field (data-extra/<collection>.js, megabytes, fetched when a card is revealed) and
   stays the authoring home — `add-places.js`, `migrate-places.js` and the admin editor write it there. The Personal Atlas has to
   know, for every card the reader has reviewed, which places it is about, WITHOUT loading the heavy collection files: so this
   script derives a light index from it, one entry per card that carries any:

       window.ATLAS_CARD_PLACES = { format: 1, digest, counts, ids: [ …every place id any card carries, sorted… ],
                                    cards: { "gr-001": [3, 17], … } }      // card id → indices into `ids` (places and polities alike)

   An id is a registry id (the gazetteer's `city:…`, `adm0:…`, `reg:…`; places.js's `pl:q…`; the history entity table's `pol:…`),
   so the same file answers "which places are this reader's?" and, read the other way, "which cards are about this place?" (the
   place card, Phase 3b). It carries no text and no coordinate — those live in the registry — so it is lazy beside places.js and
   far smaller than the heavy halves it stands in for (size measured and printed; the build fails over 200 KB, the brief's stop
   rule: propose a split rather than grow it). GENERATED: never edit; it is a pure function of the cards, so two builds are
   byte-identical (`digest` is a hash of the content, not a clock).

   SOURCES. The first line is the `sources` header every generated file under atlas/data/ carries (build-credits.js reads it).
   This file is derived from the cards' own `places` — Folio's content — and holds no third-party data (the registry rows it
   points at carry theirs), so the list is empty.

   --check  regenerate in memory and compare with the committed file; exit 1 when it lags the cards.
   Run by: migrate-places.js and add-places.js after they write `places` (so the index cannot lag), CI's check-places.js. */
"use strict";
const fs = require("fs"), path = require("path"), crypto = require("crypto");
const HERE = __dirname, ROOT = path.join(HERE, "..", "..");
const TARGET = path.join(ROOT, "atlas", "data", "card-places.js");
const OUT = path.join(HERE, "out");
const BUDGET = 200000;   // bytes, decimal: over this the brief says stop and propose a split

/* the index from a list of cards (id, places) — pure, so the tests can feed it fixtures */
function indexOf(cards) {
  const carrying = cards.filter((c) => Array.isArray(c.places) && c.places.length).sort((a, b) => (a.id < b.id ? -1 : a.id > b.id ? 1 : 0));
  const ids = [...new Set(carrying.flatMap((c) => c.places))].sort();
  const at = new Map(ids.map((id, i) => [id, i]));
  const cardsOut = {};
  for (const c of carrying) cardsOut[c.id] = [...new Set(c.places)].sort().map((id) => at.get(id));
  const counts = { cards: carrying.length, places: ids.filter((id) => !id.startsWith("pol:")).length, polities: ids.filter((id) => id.startsWith("pol:")).length, links: carrying.reduce((s, c) => s + new Set(c.places).size, 0) };
  const digest = crypto.createHash("sha256").update(JSON.stringify([ids, cardsOut])).digest("hex").slice(0, 16);
  return { format: 1, digest, counts, ids, cards: cardsOut };
}
function render(index) {
  const lines = Object.entries(index.cards).map(([id, a]) => JSON.stringify(id) + ":" + JSON.stringify(a));
  const head = JSON.stringify({ format: index.format, digest: index.digest, counts: index.counts });
  return "/* sources: [] */\n" +
    "/* atlas/data/card-places.js — GENERATED by .claude/atlas-build/build-card-places.js from the cards' `places` (docs/atlas-v2-design.md\n" +
    "   §2.8, §7 \"Phase 3b — as built\"). Do not edit. The light card-to-places index: `cards` maps a card id to indices into `ids`, the\n" +
    "   registry ids (places and polities) the card is about; the heavy `places` field in data-extra/ stays the authoring home. It\n" +
    "   carries no third-party data (the registry rows carry theirs), so `sources` above is empty. */\n" +
    "window.ATLAS_CARD_PLACES = " + head.slice(0, -1) + ",\"ids\":" + JSON.stringify(index.ids) + ",\"cards\":{\n" + lines.join(",\n") + "\n}};\n";
}
function build(opts) {
  opts = opts || {};
  const log = opts.log || console.log;
  const cards = opts.cards || require(path.join(ROOT, ".claude", "card-io.js")).loadCards().cards;
  const index = indexOf(cards), body = render(index);
  const bytes = Buffer.byteLength(body, "utf8");
  log(`card-places: ${index.counts.cards} cards → ${index.ids.length} ids (${index.counts.places} places, ${index.counts.polities} polities), ${index.counts.links} links, ${bytes} bytes (${(bytes / 1e3).toFixed(1)} KB decimal; budget ${BUDGET / 1e3} KB), digest ${index.digest}`);
  if (bytes > BUDGET) { const e = new Error("card-places.js is " + bytes + " bytes, over the " + BUDGET + "-byte budget: stop and propose a split (by collection, as data-extra/ is) before building more"); e.over = true; throw e; }
  if (opts.check) { const have = fs.existsSync(TARGET) ? fs.readFileSync(TARGET, "utf8") : ""; const ok = have === body; return { ok, why: ok ? "" : have ? "the committed file differs from what the cards build" : "atlas/data/card-places.js is missing", index, bytes }; }
  if (opts.dry) return { ok: true, index, bytes, body };
  fs.mkdirSync(OUT, { recursive: true }); fs.writeFileSync(path.join(OUT, "card-places.js"), body);
  if (opts.install) {
    const same = fs.existsSync(TARGET) && fs.readFileSync(TARGET, "utf8") === body;
    const existed = fs.existsSync(TARGET);
    if (!same) { fs.writeFileSync(TARGET, body); log("installed atlas/data/card-places.js"); } else log("atlas/data/card-places.js unchanged");
    // the credits page counts the files it read; a first install adds one (a later build changes no header)
    if (!existed) { require("./build-credits.js").build({ install: true, log: () => {} }); log("regenerated atlas/data/credits.js"); }
  }
  return { ok: true, index, bytes, body };
}
module.exports = { build, indexOf, render, TARGET, BUDGET };
if (require.main === module) {
  const argv = process.argv.slice(2);
  try {
    const r = build({ install: argv.includes("--install"), dry: argv.includes("--dry"), check: argv.includes("--check") });
    if (argv.includes("--check")) { console.log(r.ok ? "atlas/data/card-places.js is in step with the cards" : "STALE: " + r.why + " — run: node .claude/atlas-build/build-card-places.js --install"); process.exit(r.ok ? 0 : 1); }
  } catch (e) { console.error(e.message); process.exit(1); }
}
