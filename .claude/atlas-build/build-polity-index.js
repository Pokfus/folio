#!/usr/bin/env node
/* build-polity-index.js — the polities' names and the years each is on the map: atlas/data/polity-index.js
   (Atlas v2 Phase 3c, task 3; docs/atlas-v2-design.md §7 "Phase 3c — as built").

     node .claude/atlas-build/build-polity-index.js [--install] [--dry] [--check]

   WHY. The Atlas's search box finds a place whatever year the rail shows — the Roman Republic, Sumer, Karakorum — and says so, with a
   button to the nearest year it IS on the map, when the rail is somewhere else. The names and the years are in history.bin (4.7 MB, fetched
   on the rail's first touch); a keystroke in the search box must not cost that, so this file carries just what the search needs:

       window.ATLAS_POLITY_INDEX = { format: 1, digest, counts,
         polities: [ [id, name, [other names…], spanFrom, spanTo, [[from, to], …] mapped-year ranges, qid], … ],
         capitals: [ [entityId, name, lon, lat, from, to], … ] }

   A polity's RANGES are its steps (history.bin `steps`) with consecutive and overlapping ones joined — a gap between two ranges is a
   real gap in the map (Cliopatria has none for that polity in those years), so the search may offer the next range's first year and
   never a year between. Nothing is typed: a pure function of history.bin's header, byte-identical on every run. Kinds `polity`, `people` and `culture`
   (the contested and nested entities are not places a reader looks for by name; a people's or a culture's row carries its kind as an eighth element).

   SOURCES. The first line is the `sources` header every generated file under atlas/data/ carries: Cliopatria (the names and years) and
   Wikidata (the capitals), copied from history.bin's own header.

   --check  regenerate in memory and compare with the committed file; exit 1 when it lags history.bin. */
"use strict";
const fs = require("fs"), path = require("path"), crypto = require("crypto");
const HERE = __dirname, ROOT = path.join(HERE, "..", "..");
const TARGET = path.join(ROOT, "atlas", "data", "polity-index.js");
const HISTORY = path.join(ROOT, "atlas", "data", "history.bin");
const USED = ["cliopatria", "wikidata-capitals"];

/* pure: the index from a history header */
function indexOf(H) {
  const byEnt = new Map();
  for (const st of H.steps || []) { let l = byEnt.get(st[0]); if (!l) byEnt.set(st[0], l = []); l.push([st[1], st[2]]); }
  const rangesOf = (i) => {
    const l = (byEnt.get(i) || []).slice().sort((a, b) => a[0] - b[0] || a[1] - b[1]), out = [];
    for (const s of l) { const last = out[out.length - 1]; if (last && s[0] <= last[1] + 1) last[1] = Math.max(last[1], s[1]); else out.push([s[0], s[1]]); }
    return out;
  };
  const polities = [];
  (H.entities || []).forEach((e, i) => {
    if (e.kind !== "polity" && e.kind !== "people" && e.kind !== "culture" && e.kind !== "extent") return;   // 2c: a people or a culture is found by name too (element 7 says which)
    const ranges = rangesOf(i);
    const row = [e.id, e.name, (e.sourceNames || []).filter((n) => n !== e.name), e.span ? e.span[0] : ranges.length ? ranges[0][0] : 0, e.span ? e.span[1] : ranges.length ? ranges[ranges.length - 1][1] : 0, ranges, e.qid || ""];
    if (e.kind !== "polity") row.push(e.kind);
    polities.push(row);
  });
  polities.sort((a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0));
  const have = new Set(polities.map((p) => p[0]));
  const capitals = (H.cities || []).filter((c) => have.has(c.entity)).map((c) => [c.entity, c.name, c.lon, c.lat, c.from, c.to]).sort((a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : a[4] - b[4] || (a[1] < b[1] ? -1 : 1)));
  const digest = crypto.createHash("sha256").update(JSON.stringify([polities, capitals])).digest("hex").slice(0, 16);
  return { format: 1, digest, counts: { polities: polities.length, ranges: polities.reduce((s, p) => s + p[5].length, 0), capitals: capitals.length }, polities, capitals };
}
function render(ix, sources) {
  return "/* sources: " + JSON.stringify(sources) + " */\n" +
    "/* atlas/data/polity-index.js — GENERATED by .claude/atlas-build/build-polity-index.js from history.bin's header (docs/atlas-v2-design.md\n" +
    "   §7 \"Phase 3c — as built\"). Do not edit. The polities' names, the year ranges each is on the map (steps joined; a gap is a real gap) and\n" +
    "   their period capitals: what the search box needs without fetching the 4.7 MB history file. */\n" +
    "window.ATLAS_POLITY_INDEX = " + JSON.stringify({ format: ix.format, digest: ix.digest, counts: ix.counts }).slice(0, -1) +
    ",\"polities\":[\n" + ix.polities.map((r) => JSON.stringify(r)).join(",\n") + "\n],\"capitals\":[\n" + ix.capitals.map((r) => JSON.stringify(r)).join(",\n") + "\n]};\n";
}
function build(opts) {
  opts = opts || {};
  const log = opts.log || console.log;
  const F = require("./lib/format.js");
  const H = F.read(fs.readFileSync(HISTORY), { headerOnly: true }).header;
  const sources = (H.sources || []).filter((s) => USED.includes(s.id));
  if (sources.length !== USED.length) throw new Error("history.bin's header lacks a source this file claims: " + USED.join(", "));
  const ix = indexOf(H), body = render(ix, sources);
  log(`polity-index: ${ix.counts.polities} polities in ${ix.counts.ranges} year ranges, ${ix.counts.capitals} period capitals, ${Buffer.byteLength(body, "utf8")} bytes`);
  if (opts.check) { const have = fs.existsSync(TARGET) ? fs.readFileSync(TARGET, "utf8") : ""; const ok = have === body; return { ok, why: ok ? "" : have ? "the committed file differs from what history.bin builds" : "atlas/data/polity-index.js does not exist", index: ix, body }; }
  if (opts.dry) return { ok: true, index: ix, body };
  if (opts.install) {
    const existed = fs.existsSync(TARGET), same = existed && fs.readFileSync(TARGET, "utf8") === body;
    if (!same) { fs.writeFileSync(TARGET, body); log("installed atlas/data/polity-index.js"); } else log("atlas/data/polity-index.js unchanged");
    if (!existed) { require("./build-credits.js").build({ install: true, log: () => {} }); log("regenerated atlas/data/credits.js"); }
  }
  return { ok: true, index: ix, body };
}
module.exports = { build, indexOf, render, TARGET };
if (require.main === module) {
  const argv = process.argv.slice(2);
  try {
    const r = build({ install: argv.includes("--install"), dry: argv.includes("--dry"), check: argv.includes("--check") });
    if (argv.includes("--check")) { console.log(r.ok ? "atlas/data/polity-index.js is in step with history.bin" : "STALE: " + r.why + " — run: node .claude/atlas-build/build-polity-index.js --install"); process.exit(r.ok ? 0 : 1); }
  } catch (e) { console.error(e.message); process.exit(1); }
}
