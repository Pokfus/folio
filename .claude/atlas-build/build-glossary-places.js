#!/usr/bin/env node
/* build-glossary-places.js — which glossary terms can open #map2 at a registry place: atlas/data/glossary-places.js
   (Atlas v2 Phase 3c, task 2; docs/atlas-v2-design.md §2.8, §7 "Phase 3c — as built").

     node .claude/atlas-build/build-glossary-places.js [--install] [--dry] [--check]

   WHAT IT IS. The glossary popup's "show on the Atlas" button already exists for v1: a term that names a POINT
   (`GLOSSARY_PLACES`, 31 hand-given coordinates) or a COUNTRY (`GLOSSARY_MAP_COUNTRY`, 181 names) opens the old globe. For v2 the
   button opens `#map2` at the place's REGISTRY id, so the table is  slug → registry id:

       window.ATLAS_GLOSSARY_PLACES = { format: 1, digest, counts, ids: { "Lascaux": "pl:q172125", "France": "adm0:…", … } }

   · a point term resolves through places-spec.json's `glossary` (written by migrate-places.js, which resolves each coordinate
     against the gazetteer and Wikidata exactly as it resolves a card's locator: the item's own coordinate must agree, nothing
     is guessed; a term that does not resolve is left out and the migration's report says why);
   · a country term resolves by the name the map uses (`GLOSSARY_MAP_COUNTRY`'s value) to the gazetteer's ONE `country` row of
     that name or alias; a name with no such row, or two, is left out and listed.
   Terms do NOT contribute to the Personal Atlas (Q-P3 c) and nothing is written to a term: this file is read only by the
   glossary popup's button. A pure function of glossary.js, places-spec.json and the registry — byte-identical on every run.

   SOURCES. The first line is the `sources` header every generated file under atlas/data/ carries; this file carries ids only
   (the registry rows carry their sources), so the list is empty.

   --check  regenerate in memory and compare with the committed file; exit 1 when it lags. Run by migrate-places.js and CI's check-places.js. */
"use strict";
const fs = require("fs"), path = require("path"), crypto = require("crypto");
const HERE = __dirname, ROOT = path.join(HERE, "..", "..");
const TARGET = path.join(ROOT, "atlas", "data", "glossary-places.js");
const SPEC = path.join(HERE, "places-spec.json");

/* pure: the table and what could not be joined, from the glossary's two tables, the spec's resolutions and a registry */
function tableOf({ points, countries, resolved, reg, fold, isDeckKey }) {
  const ids = {}, left = [];
  for (const slug of Object.keys(points || {}).sort()) {
    const id = (resolved || {})[slug];
    if (id && reg.rows.has(id)) ids[slug] = id; else left.push({ slug, via: "point", why: id ? "the spec's id " + id + " is not in the registry" : "the migration did not resolve its coordinate to a place (see docs/atlas-places-report.md)" });
  }
  for (const slug of Object.keys(countries || {}).sort()) {
    if (isDeckKey && isDeckKey(slug)) continue;
    const name = countries[slug];
    const rows = (reg.byName.get(fold(name)) || []).filter((r) => r.kind === "country");
    if (rows.length === 1) ids[slug] = rows[0].id;
    else left.push({ slug, via: "country", why: rows.length ? name + " names " + rows.length + " country rows" : "no country row is named " + JSON.stringify(name) });
  }
  return { ids, left };
}
function render(ids) {
  const digest = crypto.createHash("sha256").update(JSON.stringify(ids)).digest("hex").slice(0, 16);
  const keys = Object.keys(ids).sort();
  const nPoint = keys.filter((k) => !/^adm0:/.test(ids[k])).length;
  const head = JSON.stringify({ format: 1, digest, counts: { terms: keys.length, points: nPoint, countries: keys.length - nPoint } });
  return "/* sources: [] */\n" +
    "/* atlas/data/glossary-places.js — GENERATED by .claude/atlas-build/build-glossary-places.js (docs/atlas-v2-design.md §2.8, §7\n" +
    "   \"Phase 3c — as built\"). Do not edit. Which glossary terms the popup's \"show on the Atlas\" button can open on #map2: term slug →\n" +
    "   registry id. Terms do not contribute to the Personal Atlas (Q-P3 c); this file carries ids only, so `sources` above is empty. */\n" +
    "window.ATLAS_GLOSSARY_PLACES = " + head.slice(0, -1) + ",\"ids\":{\n" + keys.map((k) => JSON.stringify(k) + ":" + JSON.stringify(ids[k])).join(",\n") + "\n}};\n";
}
function build(opts) {
  opts = opts || {};
  const log = opts.log || console.log;
  const R = require(path.join(ROOT, ".claude", "places-registry.js"));
  const reg = R.loadRegistry({ entities: false });
  /* the two input tables: since Phase 5 an offline file (glossary-places-input.json), no longer shipped at the foot of glossary.js */
  const w = JSON.parse(fs.readFileSync(path.join(HERE, "glossary-places-input.json"), "utf8")); w.GLOSSARY_PLACES = w.points; w.GLOSSARY_MAP_COUNTRY = w.countries;
  const spec = JSON.parse(fs.readFileSync(SPEC, "utf8"));
  const T = tableOf({ points: w.GLOSSARY_PLACES, countries: w.GLOSSARY_MAP_COUNTRY, resolved: spec.glossary, reg, fold: R.fold });
  const body = render(T.ids);
  log(`glossary-places: ${Object.keys(T.ids).length} terms get a registry place (${Object.keys(w.GLOSSARY_PLACES || {}).length - T.left.filter((l) => l.via === "point").length} of ${Object.keys(w.GLOSSARY_PLACES || {}).length} points, ${Object.keys(w.GLOSSARY_MAP_COUNTRY || {}).length - T.left.filter((l) => l.via === "country").length} of ${Object.keys(w.GLOSSARY_MAP_COUNTRY || {}).length} countries), ${Buffer.byteLength(body, "utf8")} bytes; ${T.left.length} left out`);
  for (const l of T.left) log(`  left out: ${l.slug} (${l.via}) — ${l.why}`);
  if (opts.check) { const have = fs.existsSync(TARGET) ? fs.readFileSync(TARGET, "utf8") : ""; const ok = have === body; return { ok, why: ok ? "" : have ? "the committed file differs from what the glossary and the registry build" : "atlas/data/glossary-places.js does not exist", table: T, body }; }
  if (opts.dry) return { ok: true, table: T, body };
  if (opts.install) {
    const existed = fs.existsSync(TARGET), same = existed && fs.readFileSync(TARGET, "utf8") === body;
    if (!same) { fs.writeFileSync(TARGET, body); log("installed atlas/data/glossary-places.js"); } else log("atlas/data/glossary-places.js unchanged");
    if (!existed) { require("./build-credits.js").build({ install: true, log: () => {} }); log("regenerated atlas/data/credits.js"); }
  }
  return { ok: true, table: T, body };
}
module.exports = { build, tableOf, render, TARGET };
if (require.main === module) {
  const argv = process.argv.slice(2);
  try {
    const r = build({ install: argv.includes("--install"), dry: argv.includes("--dry"), check: argv.includes("--check") });
    if (argv.includes("--check")) { console.log(r.ok ? "atlas/data/glossary-places.js is in step" : "STALE: " + r.why + " — run: node .claude/atlas-build/build-glossary-places.js --install"); process.exit(r.ok ? 0 : 1); }
  } catch (e) { console.error(e.message); process.exit(1); }
}
