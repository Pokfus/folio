// Dev-only: build us-cities.js = the LARGEST CITY of every state whose largest city is not its capital,
// as a points table for a map card's dot. Run: node .claude/build-us-cities.js
//
//   window.US_CITIES = { "<key>": { s: "<state>", n?: "<display name>", c: [lon, lat] } }
//
// It is `us-states.js`'s US_CAPITALS one table over, and for that table's reason: the Largest cities deck
// (geo-701 … geo-750) marks a city with a dot, and a coordinate typed by hand is a dot a degree out that
// still draws. So WHICH city is DECLARED — it is the "Largest city" row of each state card's own facts
// grid, read out of data.js rather than restated here, so the deck and the grid cannot disagree — and
// the COORDINATE is read off Natural Earth's 10m populated-places record for that city in that state,
// the dataset the capitals come from.
//
// It is its OWN FILE rather than a second table inside us-states.js because that file is generated by a
// builder that refetches 40 MB and re-simplifies all fifty states; re-running it to add thirty-odd points
// would put the whole state geometry at the mercy of whatever Natural Earth changed upstream since. This
// file rides in the same lazy `usstates` bundle and costs a few kilobytes.
//
// KEYS: a city is keyed by its bare name unless that name is taken — by a capital in US_CAPITALS
// (Charleston is West Virginia's capital and South Carolina's largest city) or by another row here (two
// Portlands). A taken name is keyed "<city>, <state>" and carries `n`, the name the revealed label prints.
//
// EVERY POINT IS TESTED FOR FALLING INSIDE ITS OWN STATE'S POLYGON before it is written, against the
// shapes in us-states.js that the card will actually shade — the check `build-china-provinces.js` makes,
// and the one a name match cannot: Natural Earth carries several Portlands, Kansas Cities and Charlestons.
const fs = require("fs"), path = require("path");
const PLACES_URL = "https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_10m_populated_places.geojson";
const CACHE_DIR = path.join(__dirname, "ne-cache");
const PLACES_CACHE = path.join(CACHE_DIR, "ne_10m_populated_places.geojson");
const ROOT = path.join(__dirname, "..");

function loadWindow(file) { const w = {}; new Function("window", fs.readFileSync(file, "utf8"))(w); return w; }
function inRing(x, y, r) {
  let inside = false;
  for (let i = 0, j = r.length - 1; i < r.length; j = i++) {
    const xi = r[i][0], yi = r[i][1], xj = r[j][0], yj = r[j][1];
    if ((yi > y) !== (yj > y) && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}
const inShape = (pt, rings) => rings.reduce((a, r) => (inRing(pt[0], pt[1], r) ? !a : a), false);   // even-odd, like the renderer
/* Degrees from a point to the nearest edge of a shape, lon scaled by cos(lat) so it reads as distance. */
function edgeDist(pt, rings) {
  const k = Math.cos((pt[1] * Math.PI) / 180);
  let best = Infinity;
  for (const r of rings) for (let i = 1; i < r.length; i++) {
    const ax = r[i - 1][0] * k, ay = r[i - 1][1], bx = r[i][0] * k, by = r[i][1], px = pt[0] * k, py = pt[1];
    const dx = bx - ax, dy = by - ay, L = dx * dx + dy * dy || 1e-12;
    const t = Math.max(0, Math.min(1, ((px - ax) * dx + (py - ay) * dy) / L));
    best = Math.min(best, Math.hypot(px - (ax + t * dx), py - (ay + t * dy)));
  }
  return best;
}
/* A WATERFRONT CITY CAN SIT JUST OFF THE STATE'S TRACED SHORE — Detroit's point is on the Detroit River,
   which the lakes-clipped layer cuts out of Michigan — and that is a fact about the tracing rather than
   about the city. `world-capitals.js` meets the same thing on atolls and deliberately does not snap, since
   moving the city to flatter the map is the worse error. So a point within NEAR_DEG of its own state's
   edge is accepted and REPORTED; anything further out is a wrong record and refuses. */
const NEAR_DEG = 0.05;

(async () => {
  if (process.argv.includes("--refetch")) { try { fs.unlinkSync(PLACES_CACHE); } catch (e) {} }
  if (!fs.existsSync(PLACES_CACHE)) {
    console.log("fetching", PLACES_URL);
    const r = await fetch(PLACES_URL);
    if (!r.ok) { console.error("HTTP " + r.status); process.exit(1); }
    fs.mkdirSync(CACHE_DIR, { recursive: true });
    fs.writeFileSync(PLACES_CACHE, Buffer.from(await r.arrayBuffer()));
  } else console.log("using cached " + path.relative(process.cwd(), PLACES_CACHE) + " (--refetch to replace)");

  global.window = {};
  const { loadCards } = require("./card-io.js");
  const cards = loadCards().cards.filter((c) => /^geo-0\d\d$/.test(c.id));
  const want = [];
  for (const c of cards) {
    const f = Object.fromEntries(c.facts || []);
    if (!f.Capital || !f["Largest city"]) { console.error("ERROR: " + c.id + " has no Capital / Largest city row"); process.exit(1); }
    if (f.Capital !== f["Largest city"]) want.push({ state: c.map.key, city: f["Largest city"], num: c.num });
  }
  const st = loadWindow(path.join(ROOT, "us-states.js"));
  const shapes = Object.fromEntries(st.US_STATES.map((s) => [s.n, s.p]));
  const caps = st.US_CAPITALS;

  /* Natural Earth names a few of these differently from the grid; the alias is the ONLY thing declared by
     hand here, and each is a spelling rather than a different place. */
  const NE_NAME = { "New York City": ["New York"], "Louisville": ["Louisville", "Louisville/Jefferson County"] };
  const places = JSON.parse(fs.readFileSync(PLACES_CACHE, "utf8")).features;
  const Q4 = (v) => Math.round(v * 1e4) / 1e4;
  const rows = [];
  for (const w of want) {
    const names = NE_NAME[w.city] || [w.city];
    const cands = places.filter((f) => {
      const p = f.properties || {};
      return (p.ADM0NAME || p.adm0name) === "United States of America" &&
        String(p.ADM1NAME || p.adm1name || "").replace(/\s+/g, " ").trim() === w.state &&
        names.includes(String(p.NAME || p.name || "").replace(/\s+/g, " ").trim()) &&
        f.geometry && f.geometry.type === "Point";
    });
    if (cands.length !== 1) { console.error("ERROR: " + cands.length + " Natural Earth records for " + w.city + ", " + w.state); process.exit(1); }
    const g = cands[0].geometry.coordinates, c = [Q4(g[0]), Q4(g[1])];
    if (!shapes[w.state]) { console.error("ERROR: no shape for " + w.state); process.exit(1); }
    if (!inShape(c, shapes[w.state])) {
      const d = edgeDist(c, shapes[w.state]);
      if (d > NEAR_DEG) { console.error("ERROR: " + w.city + " at " + c + " falls " + d.toFixed(3) + " deg outside " + w.state + "'s own polygon"); process.exit(1); }
      console.log("  · " + w.city + " stands " + (d * 111).toFixed(1) + " km off " + w.state + "'s traced shore — kept, not snapped");
    }
    rows.push({ city: w.city, state: w.state, c });
  }
  const out = {};
  const count = {};
  rows.forEach((r) => { count[r.city] = (count[r.city] || 0) + 1; });
  for (const r of rows.sort((a, b) => a.city.localeCompare(b.city) || a.state.localeCompare(b.state))) {
    const taken = caps[r.city] || count[r.city] > 1;
    const key = taken ? r.city + ", " + r.state : r.city;
    out[key] = taken ? { s: r.state, n: r.city, c: r.c } : { s: r.state, c: r.c };
  }
  const body = "/* The largest city of every US state whose largest city is not its capital — a points table for the\n" +
    "   Largest cities deck's dot, beside us-states.js's US_CAPITALS. Keyed by city, or \"<city>, <state>\" where\n" +
    "   the bare name is a capital's or another row's (then `n` is the name the label prints). s=the state it\n" +
    "   stands in, c=[lon,lat] at 4dp from Natural Earth 10m populated places, each tested inside its own\n" +
    "   state's polygon. The CITY is the \"Largest city\" row of that state's own card.\n" +
    "   LAZY — part of the `usstates` bundle. Built by .claude/build-us-cities.js. Do not hand-edit. */\n" +
    "window.US_CITIES = " + JSON.stringify(out) + ";\n";
  const dest = path.join(ROOT, "us-cities.js");
  fs.writeFileSync(dest, body);
  const back = loadWindow(dest).US_CITIES;
  if (Object.keys(back).length !== want.length) { console.error("ERROR: re-parse gave " + Object.keys(back).length + " rows, expected " + want.length); process.exit(1); }
  console.log("wrote us-cities.js: " + want.length + " cities, " + Buffer.byteLength(body) + " bytes");
  for (const k of Object.keys(out)) console.log("  " + k.padEnd(28) + out[k].s);
})().catch((e) => { console.error("ERR", e.stack || e.message); process.exit(1); });
